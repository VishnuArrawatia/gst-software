-- 15_gstr1_draft_filed_reconciliation.sql
--
-- Stage 1, part 2: sales register -> GSTR-1.
--
-- migration 02 gave us sales_invoices (the books side) and two EMPTY shells —
-- gstr1_filings (one summary row per filed return) and sales_reconciliation
-- (one outcome row per book invoice). Neither could ever hold a comparison,
-- because there was nowhere to put the per-invoice detail of a filed GSTR-1:
-- the portal's B2B sheet is one row per recipient-invoice, and gstr1_filings
-- only has four counts and six totals.
--
-- So this migration adds the missing middle:
--
--   gstr1_documents            one row per document, for BOTH the draft we
--                              compute from books and the return as filed on
--                              the portal. `source` is what tells them apart.
--   gstr1_summary_comparison   per GSTIN + period + table (B2B/B2CL/B2CS/
--                              CDNR): draft vs filed counts and money.
--   gstr1_recon_runs           one row per reconciliation run — who ran it,
--                              over what, and what came out.
--
-- and extends sales_reconciliation so an outcome can point at the draft row
-- and the filed row it is about, not just the book invoice.
--
-- On the enum: sales_recon_status already had the right statuses but was
-- missing the two failures that only exist once you compare a draft against a
-- filed return rather than a single source against the other — the document
-- went into a different table than we drafted it into, or it named a different
-- recipient. Adding enum values is additive and cannot invalidate rows that
-- already exist.
--
-- On the period lock: gstr1_documents is deliberately NOT guarded by
-- block_write_to_locked_period. A locked period means "these books are
-- settled, do not recompute them" — but the portal's filed return is a
-- historical fact. Refusing to record what was actually filed, because the
-- books were locked, would make the reconciliation impossible to complete for
-- exactly the periods that most need it. The DRAFT side is protected instead,
-- by regenerating drafts only from unlocked periods (see buildDraftPeriods).

-- ===================================================================
-- Per-document rows for the draft and for the filed return
-- ===================================================================

-- 'draft' rows are computed from sales_invoices and may be regenerated.
-- 'filed' rows are what the taxpayer actually submitted; they are evidence and
-- are never regenerated.
CREATE TYPE gstr1_doc_source AS ENUM ('draft', 'filed');

-- The four outward tables. B2CS is the exception: it is not a document list,
-- it is an aggregate by place of supply and rate, so its rows carry a
-- synthetic key instead of an invoice number (see aggregateKey).
CREATE TYPE gstr1_table_type AS ENUM ('B2B', 'B2CL', 'B2CS', 'CDNR');

CREATE TABLE IF NOT EXISTS gstr1_documents (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gstin_id                INTEGER NOT NULL,
    financial_year          VARCHAR(9) NOT NULL,
    period                  VARCHAR(7) NOT NULL,

    source                  gstr1_doc_source  NOT NULL,
    table_type              gstr1_table_type  NOT NULL,

    invoice_number_raw      VARCHAR(100),
    invoice_number_norm     VARCHAR(100) NOT NULL,
    invoice_date            DATE,

    invoice_type            VARCHAR(8)  NOT NULL DEFAULT 'R',
    recipient_gstin_raw     VARCHAR(15),
    recipient_gstin_norm    VARCHAR(15),
    recipient_name          VARCHAR(255),
    place_of_supply         VARCHAR(100),
    pos_code                VARCHAR(2),
    reverse_charge          BOOLEAN     NOT NULL DEFAULT false,
    hsn                     VARCHAR(8),

    taxable_value           NUMERIC(15,2) NOT NULL DEFAULT 0,
    igst                    NUMERIC(15,2) NOT NULL DEFAULT 0,
    cgst                    NUMERIC(15,2) NOT NULL DEFAULT 0,
    sgst                    NUMERIC(15,2) NOT NULL DEFAULT 0,
    cess                    NUMERIC(15,2) NOT NULL DEFAULT 0,
    invoice_value           NUMERIC(15,2) NOT NULL DEFAULT 0,
    -- Populated on B2CS rows only: the slab the amount rolls up into.
    rate                    NUMERIC(6,3),

    note_ref_number         VARCHAR(100),
    note_ref_date           DATE,

    -- The book invoice this row was drafted from. NULL for filed rows that
    -- have no books counterpart at all — that is the whole point of finding
    -- them.
    sales_invoice_id        BIGINT,
    uploaded_file_id        INTEGER,
    source_row_number       INTEGER,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_g1doc_gstin   FOREIGN KEY (gstin_id)         REFERENCES gstins (id)         ON DELETE RESTRICT,
    CONSTRAINT fk_g1doc_sales   FOREIGN KEY (sales_invoice_id) REFERENCES sales_invoices (id) ON DELETE SET NULL,
    -- A credit note we DRAFT without a reference is a note the portal will
    -- reject. Restricted to drafts on purpose: if the portal accepted a note
    -- without a reference, the filed row has to be recordable, because
    -- recording what was actually filed is the one thing this table cannot
    -- refuse to do.
    CONSTRAINT ck_g1doc_cdnr_ref CHECK (
        source <> 'draft' OR table_type <> 'CDNR' OR invoice_type <> 'CDNR'
        OR (note_ref_number IS NOT NULL AND note_ref_date IS NOT NULL)
    ),
    CONSTRAINT ck_g1doc_b2cs_rate CHECK (table_type <> 'B2CS' OR rate IS NOT NULL)
);

-- Re-running a draft or re-importing the same portal file must collide, not
-- duplicate. The key is the same shape as sales_invoices: normalised invoice
-- number plus date, because "INV/001" and "inv-001" are one invoice.
-- `source` is in the key so a draft and the filed row it becomes coexist.
CREATE UNIQUE INDEX IF NOT EXISTS uq_gstr1_document
    ON gstr1_documents (gstin_id, period, source, invoice_number_norm, COALESCE(invoice_date, DATE '1900-01-01'));

CREATE INDEX IF NOT EXISTS idx_g1doc_lookup  ON gstr1_documents (gstin_id, period, source, table_type);
CREATE INDEX IF NOT EXISTS idx_g1doc_sales    ON gstr1_documents (sales_invoice_id) WHERE sales_invoice_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_g1doc_recipient ON gstr1_documents (recipient_gstin_norm) WHERE recipient_gstin_norm IS NOT NULL;
-- Unmatched filed rows are the ones a human must chase. Partial index, because
-- that set is a fraction of the table.
CREATE INDEX IF NOT EXISTS idx_g1doc_unmatched
    ON gstr1_documents (gstin_id, period)
    WHERE source = 'filed' AND sales_invoice_id IS NULL;

-- ===================================================================
-- Recon outcomes now name both sides
-- ===================================================================

-- A document can be drafted into one table and filed into another: an invoice
-- to a customer whose GSTIN was entered late, or omitted, lands in B2CS instead
-- of B2B. Both sides are individually "fine", so there is no amount
-- difference to report — the difference is the table itself.
ALTER TYPE sales_recon_status ADD VALUE IF NOT EXISTS 'Table Mismatch';
-- Same idea for the recipient: a B2B row filed against a different GSTIN than
-- the books recorded. Worth a separate status because it is a data-entry
-- problem in the books, not a filing problem.
ALTER TYPE sales_recon_status ADD VALUE IF NOT EXISTS 'Recipient Mismatch';
-- Drafted but the filed return carries no counterpart at all, and no book
-- invoice either — only reachable on filed-side rows.
ALTER TYPE sales_recon_status ADD VALUE IF NOT EXISTS 'Not In Draft';

ALTER TABLE sales_reconciliation ADD COLUMN IF NOT EXISTS financial_year     VARCHAR(9);
ALTER TABLE sales_reconciliation ADD COLUMN IF NOT EXISTS table_type         gstr1_table_type;
ALTER TABLE sales_reconciliation ADD COLUMN IF NOT EXISTS gstr1_draft_id      BIGINT;
ALTER TABLE sales_reconciliation ADD COLUMN IF NOT EXISTS gstr1_filed_id      BIGINT;
ALTER TABLE sales_reconciliation ADD COLUMN IF NOT EXISTS draft_taxable       NUMERIC(15,2);
ALTER TABLE sales_reconciliation ADD COLUMN IF NOT EXISTS draft_tax           NUMERIC(15,2);
ALTER TABLE sales_reconciliation ADD COLUMN IF NOT EXISTS filed_taxable       NUMERIC(15,2);
ALTER TABLE sales_reconciliation ADD COLUMN IF NOT EXISTS filed_tax           NUMERIC(15,2);
ALTER TABLE sales_reconciliation ADD COLUMN IF NOT EXISTS difference_json      JSONB;

ALTER TABLE sales_reconciliation
    ADD CONSTRAINT fk_sr_draft FOREIGN KEY (gstr1_draft_id) REFERENCES gstr1_documents (id) ON DELETE SET NULL,
    ADD CONSTRAINT fk_sr_filed FOREIGN KEY (gstr1_filed_id) REFERENCES gstr1_documents (id) ON DELETE SET NULL;

-- uq_sales_recon is on sales_invoice_id alone, which silently caps the table
-- at one outcome per book invoice — correct for the purchase side, wrong here.
-- A single book invoice can be drafted into B2B and also appear as a
-- mismatching B2CS aggregate, and the filed side needs its own rows.
DROP INDEX IF EXISTS uq_sales_recon;
CREATE UNIQUE INDEX IF NOT EXISTS uq_sales_recon_v2
    ON sales_reconciliation (COALESCE(sales_invoice_id, -1), COALESCE(gstr1_filed_id, -1), table_type);

CREATE INDEX IF NOT EXISTS idx_sr_period
    ON sales_reconciliation (gstin_id, financial_year, period);

-- ===================================================================
-- Table-level comparison
-- ===================================================================
--
-- Invoice-level matching cannot catch a B2CS problem on its own: B2CS rows are
-- aggregates, so a wrong POS or a wrong slab shows up as a small difference
-- spread across many documents. This table is the one number that answers
-- "does the return foot?", per table.
CREATE TABLE IF NOT EXISTS gstr1_summary_comparison (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gstin_id            INTEGER NOT NULL,
    financial_year      VARCHAR(9) NOT NULL,
    period              VARCHAR(7) NOT NULL,
    table_type          gstr1_table_type NOT NULL,

    draft_count         INTEGER      NOT NULL DEFAULT 0,
    filed_count         INTEGER      NOT NULL DEFAULT 0,
    draft_taxable       NUMERIC(15,2) NOT NULL DEFAULT 0,
    filed_taxable       NUMERIC(15,2) NOT NULL DEFAULT 0,
    draft_tax           NUMERIC(15,2) NOT NULL DEFAULT 0,
    filed_tax           NUMERIC(15,2) NOT NULL DEFAULT 0,

    taxable_difference  NUMERIC(15,2) NOT NULL DEFAULT 0,
    tax_difference      NUMERIC(15,2) NOT NULL DEFAULT 0,
    -- 'OK' when both differences are within a rupee, which is the tolerance
    -- GST itself allows on a return.
    status              VARCHAR(16) NOT NULL DEFAULT 'OK',
    computed_at         TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_g1sc_gstin FOREIGN KEY (gstin_id) REFERENCES gstins (id) ON DELETE RESTRICT,
    CONSTRAINT uq_gstr1_summary UNIQUE (gstin_id, period, table_type),
    CONSTRAINT ck_g1sc_status CHECK (status IN ('OK', 'Taxable Diff', 'Tax Diff', 'Both Diff', 'Count Diff', 'Missing Side'))
);

-- ===================================================================
-- Run history
-- ===================================================================
--
-- Reconciliation is re-run after every correction, so "what did the CA see
-- last Friday" has to be answerable. One row per run.
CREATE TABLE IF NOT EXISTS gstr1_recon_runs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gstin_id            INTEGER NOT NULL,
    financial_year      VARCHAR(9) NOT NULL,
    period              VARCHAR(7) NOT NULL,

    draft_documents     INTEGER NOT NULL DEFAULT 0,
    filed_documents     INTEGER NOT NULL DEFAULT 0,
    matched             INTEGER NOT NULL DEFAULT 0,
    not_declared        INTEGER NOT NULL DEFAULT 0,
    declared_not_in_books INTEGER NOT NULL DEFAULT 0,
    amount_mismatch     INTEGER NOT NULL DEFAULT 0,
    table_mismatch      INTEGER NOT NULL DEFAULT 0,
    recipient_mismatch  INTEGER NOT NULL DEFAULT 0,
    credit_note_missing_ref INTEGER NOT NULL DEFAULT 0,
    duplicates          INTEGER NOT NULL DEFAULT 0,

    taxable_difference  NUMERIC(15,2) NOT NULL DEFAULT 0,
    tax_difference      NUMERIC(15,2) NOT NULL DEFAULT 0,
    -- True when a filed return exists for the period. A draft compared against
    -- nothing is not a reconciliation, and the UI must say so rather than
    -- showing a clean result.
    has_filed_data      BOOLEAN NOT NULL DEFAULT false,
    notes               TEXT,
    run_by              INTEGER REFERENCES users (id) ON DELETE SET NULL,
    ran_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_g1rr_gstin FOREIGN KEY (gstin_id) REFERENCES gstins (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_g1rr_lookup ON gstr1_recon_runs (gstin_id, period, ran_at DESC);

-- ===================================================================
-- The screen in one query
-- ===================================================================
--
-- Books vs draft vs filed for one GSTIN and period, with the outcome attached.
-- LEFT JOINs from sales_invoices so an invoice that was never declared still
-- appears — an INNER JOIN would silently drop exactly the rows the CA is
-- looking for.
CREATE OR REPLACE VIEW v_gstr1_reconciliation AS
SELECT
    g.gstin_number,
    c.name                                   AS company_name,
    si.gstin_id,
    si.financial_year,
    si.period,

    si.id                                    AS sales_invoice_id,
    si.invoice_number_raw,
    si.invoice_number_norm,
    si.invoice_date,
    si.customer_name,
    si.customer_gstin_norm,
    si.invoice_type,
    si.taxable_value                         AS books_taxable,
    si.igst + si.cgst + si.sgst + si.cess    AS books_tax,

    dd.id                                    AS draft_id,
    dd.table_type                            AS draft_table_type,
    dd.taxable_value                         AS draft_taxable,
    dd.igst + dd.cgst + dd.sgst + dd.cess    AS draft_tax,

    fd.id                                    AS filed_id,
    fd.table_type                            AS filed_table_type,
    fd.taxable_value                         AS filed_taxable,
    fd.igst + fd.cgst + fd.sgst + fd.cess    AS filed_tax,

    sr.status,
    sr.difference_amount,
    sr.difference_json,
    COALESCE(fd.taxable_value, 0) - COALESCE(dd.taxable_value, 0) AS taxable_diff,
    COALESCE(sr.resolved_at, sr.created_at) AS last_updated,
    sr.resolved_by
FROM sales_invoices si
JOIN gstins    g  ON g.id = si.gstin_id
JOIN companies c  ON c.id = si.company_id
LEFT JOIN gstr1_documents dd ON dd.sales_invoice_id = si.id AND dd.source = 'draft'
LEFT JOIN gstr1_documents fd ON fd.sales_invoice_id = si.id AND fd.source = 'filed'
LEFT JOIN sales_reconciliation sr
       ON sr.gstr1_draft_id = dd.id OR sr.gstr1_filed_id = fd.id
WHERE NOT si.is_deleted;