-- GST-SOFTWARE — Phase 2b: the sales register is ITEM-wise
--
-- `sales_invoices` holds one row per invoice: one HSN, one rate, one money
-- block. That is the right shape for the return tables, and the wrong shape for
-- the input. The SAP sales register gives one row per ITEM / tax-rate line, and
-- GSTR-1's HSN summary (table 12) is grouped by HSN/SAC + UQC + rate and carries
-- a QUANTITY — none of which survives an invoice-level import.
--
-- So the item lines get their own child table. Two consequences, both deliberate:
--
--   * an invoice total is counted ONCE, on the parent row. Repeating the item
--     rows into `sales_invoices` used to inflate the invoice value by a whole
--     repeat of itself for every extra item line (measured: +57,500 on a
--     2-line invoice), so the item money is NEVER summed into the parent. The
--     parent's taxable/tax figures are the sum of its items, computed by the
--     importer once.
--
--   * a second item can no longer overwrite the first. The unique index on the
--     parent is (gstin_id, invoice_number_norm, invoice_date); without a child
--     table, the second row of a 2-item invoice collided with the first and
--     overwrote it.
--
-- The unique key here is (sales_invoice_id, line_no), so re-uploading the same
-- register updates a line instead of duplicating it.

-- ===================================================================
-- Item lines
-- ===================================================================

CREATE TABLE IF NOT EXISTS sales_invoice_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_invoice_id    BIGINT NOT NULL,

    -- The serial within the invoice. This is the portal's `itms[].num`, and it
    -- is what makes a re-import idempotent. The importer always sets it: when
    -- the register has no Line No column, the line's position is used.
    line_no             INTEGER NOT NULL,

    item_code           VARCHAR(50),
    item_description    VARCHAR(255),
    hsn                 VARCHAR(8),
    uqc                 VARCHAR(10),
    quantity            NUMERIC(15,3),
    gst_rate            NUMERIC(6,3),

    taxable_value       NUMERIC(15,2) NOT NULL DEFAULT 0,
    igst                NUMERIC(15,2) NOT NULL DEFAULT 0,
    cgst                NUMERIC(15,2) NOT NULL DEFAULT 0,
    sgst                NUMERIC(15,2) NOT NULL DEFAULT 0,
    cess                NUMERIC(15,2) NOT NULL DEFAULT 0,

    -- A break-up OF `taxable_value`, never an amount on top of it: freight on
    -- which GST is charged is taxable, so it is already inside the taxable
    -- value. These columns only show how much of it was freight.
    freight             NUMERIC(15,2),
    other_charges       NUMERIC(15,2),

    source_row_number   INTEGER,
    raw_json            JSONB,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_sii_invoice FOREIGN KEY (sales_invoice_id)
        REFERENCES sales_invoices (id) ON DELETE CASCADE,
    CONSTRAINT ck_sii_line_no CHECK (line_no > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_sales_item_line
    ON sales_invoice_items (sales_invoice_id, line_no);
CREATE INDEX IF NOT EXISTS idx_sii_hsn ON sales_invoice_items (hsn);
CREATE INDEX IF NOT EXISTS idx_sii_invoice ON sales_invoice_items (sales_invoice_id);

COMMENT ON TABLE sales_invoice_items IS
  'One row per invoice ITEM / tax-rate line. GSTR-1 table 12 (HSN summary) and the per-invoice itms[] array are built from here.';

-- ===================================================================
-- Invoice-level columns the item-wise register adds
-- ===================================================================
--
-- All nullable / defaulted, so an existing invoice-level register still loads
-- and every query written before this migration keeps working unchanged.

ALTER TABLE sales_invoices
    ADD COLUMN IF NOT EXISTS recipient_type         VARCHAR(20),
    ADD COLUMN IF NOT EXISTS item_count             INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS e_commerce_gstin       VARCHAR(15),
    ADD COLUMN IF NOT EXISTS doc_nature             VARCHAR(100),
    ADD COLUMN IF NOT EXISTS doc_series_from        INTEGER,
    ADD COLUMN IF NOT EXISTS doc_series_to          INTEGER,
    ADD COLUMN IF NOT EXISTS doc_series_cancelled   INTEGER,
    -- B2BA / CDNRA: the FILED invoice this row corrects.
    ADD COLUMN IF NOT EXISTS amendment_invoice_number VARCHAR(100),
    ADD COLUMN IF NOT EXISTS amendment_invoice_date   DATE;

COMMENT ON COLUMN sales_invoices.item_count IS
  'How many item lines this invoice carried. 0 for an invoice-level import.';
COMMENT ON COLUMN sales_invoices.amendment_invoice_number IS
  'B2BA / CDNRA — the filed invoice number being amended, when this row amends one.';

