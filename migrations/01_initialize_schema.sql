-- 4. Reconciliation corrections numeric‑field validation (optional)
CREATE OR REPLACE FUNCTION trg_corr_value_check()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.field_name IN ('taxable_value','igst','cgst','sgst','cess','invoice_total') THEN
        IF NEW.old_value !~ '^\d+(\.\d{1,2})?$' OR NEW.new_value !~ '^\d+(\.\d{1,2})?$' THEN
            RAISE EXCEPTION 'Numeric correction fields must contain a valid numeric string';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_corr_value_check_ins
BEFORE INSERT ON reconciliation_corrections
