-- Triggers for consistency checks

-- 1. GSTIN → Unit → Company consistency
CREATE OR REPLACE FUNCTION trg_gstin_unit_company_match()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.unit_id IS NOT NULL THEN
        IF NOT EXISTS (
            SELECT 1 FROM units u
            WHERE u.id = NEW.unit_id
              AND u.company_id = NEW.company_id
        ) THEN
            RAISE EXCEPTION 'GSTIN unit_id % does not belong to the same company %', NEW.unit_id, NEW.company_id;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_gstin_unit_company_match_ins
BEFORE INSERT ON gstins
FOR EACH ROW EXECUTE FUNCTION trg_gstin_unit_company_match();

CREATE TRIGGER tg_gstin_unit_company_match_upd
BEFORE UPDATE OF unit_id, company_id ON gstins
FOR EACH ROW EXECUTE FUNCTION trg_gstin_unit_company_match();

-- 2. Purchase transaction (bills & GSTR2B) company/unit consistency with GSTIN
CREATE OR REPLACE FUNCTION trg_txn_company_unit_consistency()
RETURNS TRIGGER AS $$
DECLARE
    v_company_id INTEGER;
    v_unit_id INTEGER;
BEGIN
    SELECT company_id, unit_id INTO v_company_id, v_unit_id FROM gstins WHERE id = NEW.gstin_id;

    IF v_company_id IS NULL THEN
        RAISE EXCEPTION 'GSTIN % not found', NEW.gstin_id;
    END IF;

    IF NEW.company_id <> v_company_id THEN
        RAISE EXCEPTION 'company_id % does not match GSTIN''s company %', NEW.company_id, v_company_id;
    END IF;

    -- unit_id may be NULL on GSTIN; if GSTIN.unit_id is not null then enforce match
    IF v_unit_id IS NOT NULL AND NEW.unit_id <> v_unit_id THEN
        RAISE EXCEPTION 'unit_id % does not match GSTIN''s unit %', NEW.unit_id, v_unit_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Apply to purchase_bills
CREATE TRIGGER tg_pb_company_unit_consistency_ins
BEFORE INSERT ON purchase_bills
FOR EACH ROW EXECUTE FUNCTION trg_txn_company_unit_consistency();

CREATE TRIGGER tg_pb_company_unit_consistency_upd
BEFORE UPDATE OF company_id, unit_id, gstin_id ON purchase_bills
FOR EACH ROW EXECUTE FUNCTION trg_txn_company_unit_consistency();

-- Apply to gstr2b_records
CREATE TRIGGER tg_gstr_company_unit_consistency_ins
BEFORE INSERT ON gstr2b_records
FOR EACH ROW EXECUTE FUNCTION trg_txn_company_unit_consistency();

CREATE TRIGGER tg_gstr_company_unit_consistency_upd
BEFORE UPDATE OF company_id, unit_id, gstin_id ON gstr2b_records
FOR EACH ROW EXECUTE FUNCTION trg_txn_company_unit_consistency();

-- 3. Financial year / period referential integrity
--
-- PostgreSQL forbids sub-queries inside a CHECK constraint ("cannot use
-- subquery in check constraint"), so the original MySQL-style
-- `CHECK (fy IN (SELECT ...))` cannot work here. The financial year gets a
-- real FOREIGN KEY; the (financial_year, period) pair gets a trigger, because
-- periods is keyed by financial_year_id and cannot be reached by a plain FK.
ALTER TABLE purchase_bills
    ADD CONSTRAINT fk_pb_financial_year FOREIGN KEY (financial_year)
        REFERENCES financial_years (year_code) ON UPDATE CASCADE ON DELETE RESTRICT;

ALTER TABLE gstr2b_records
    ADD CONSTRAINT fk_gstr_financial_year FOREIGN KEY (financial_year)
        REFERENCES financial_years (year_code) ON UPDATE CASCADE ON DELETE RESTRICT;

ALTER TABLE period_locks
    ADD CONSTRAINT fk_pl_financial_year FOREIGN KEY (financial_year)
        REFERENCES financial_years (year_code) ON UPDATE CASCADE ON DELETE RESTRICT;

CREATE OR REPLACE FUNCTION trg_check_fy_period()
RETURNS TRIGGER AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM periods p
        JOIN financial_years fy ON fy.id = p.financial_year_id
        WHERE fy.year_code = NEW.financial_year
          AND p.period_code = NEW.period
    ) THEN
        RAISE EXCEPTION
            'Invalid period % for financial year % — add it to the periods table first.',
            NEW.period, NEW.financial_year
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tg_pb_fy_period ON purchase_bills;
CREATE TRIGGER tg_pb_fy_period BEFORE INSERT OR UPDATE ON purchase_bills
    FOR EACH ROW EXECUTE FUNCTION trg_check_fy_period();

