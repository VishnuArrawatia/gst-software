CREATE TRIGGER tg_corr_value_check_upd
BEFORE UPDATE ON reconciliation_corrections
FOR EACH ROW EXECUTE FUNCTION trg_corr_value_check();

-- 5. Immutable audit trail trigger
CREATE OR REPLACE FUNCTION fn_audit_log()
RETURNS TRIGGER AS $$
DECLARE
    v_user_id INTEGER;
BEGIN
    BEGIN
        v_user_id := current_setting('app.current_user_id')::INTEGER;
    EXCEPTION
        WHEN OTHERS THEN
            v_user_id := NULL;
    END;

    IF TG_OP = 'INSERT' THEN
        INSERT INTO audit_logs (user_id, action, entity_type, entity_id, old_value, new_value)
        VALUES (v_user_id, 'INSERT', TG_TABLE_NAME, NEW.id, NULL, to_jsonb(NEW));
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO audit_logs (user_id, action, entity_type, entity_id, old_value, new_value)
        VALUES (v_user_id, 'UPDATE', TG_TABLE_NAME, NEW.id, to_jsonb(OLD), to_jsonb(NEW));
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        INSERT INTO audit_logs (user_id, action, entity_type, entity_id, old_value, new_value)
        VALUES (v_user_id, 'DELETE', TG_TABLE_NAME, OLD.id, to_jsonb(OLD), NULL);
        RETURN OLD;
    END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Attach audit trigger to core tables
DO $$
DECLARE
    tbl TEXT;
    core_tables TEXT[] := ARRAY[
        'companies','units','gstins','users','roles','permissions',
        'user_roles','role_permissions','parties','financial_years','periods',
        'uploaded_files','purchase_bills','gstr2b_records',
        'purchase_reconciliation','reconciliation_corrections','period_locks'
    ];
BEGIN
    FOREACH tbl IN ARRAY core_tables LOOP
        EXECUTE format('CREATE TRIGGER tg_audit_%I AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION fn_audit_log();', tbl, tbl);
    END LOOP;
END $$;
