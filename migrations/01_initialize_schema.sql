-- Phase-1 PostgreSQL schema for GST-SOFTWARE,
-- This file contains the complete database definition, all constraints, indexes and triggers required for Phase 1.

-- Enable extension for uuid-ossp if needed (not used in this schema)

-- Table: companies
CREATE TABLE companies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    legal_name VARCHAR(255),
    tax_identifier VARCHAR(100),
    status SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by INTEGER,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by INTEGER,
    CONSTRAINT chk_company_status CHECK (status IN (0,1))
);
CREATE UNIQUE INDEX uq_companies_name ON companies (LOWER(name));

-- Table: units
CREATE TABLE units (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL,
    status SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by INTEGER,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by INTEGER,
    CONSTRAINT chk_unit_status CHECK (status IN (0,1)),
    -- CONSTRAINT uq_units_company_name UNIQUE (company_id, LOWER(name)),
    CONSTRAINT fk_units_company FOREIGN KEY (company_id)
        REFERENCES companies (id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE UNIQUE INDEX uq_units_company_name ON units (company_id, LOWER(name));

-- Table: gstins
CREATE TABLE gstins (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL,
    unit_id INTEGER,
    gstin_number VARCHAR(15) NOT NULL,
    legal_name VARCHAR(255),
    trade_name VARCHAR(255),
    state_code CHAR(2),
    status SMALLINT NOT NULL DEFAULT 1,
    effective_from DATE,
    effective_to DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by INTEGER,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by INTEGER,
    CONSTRAINT chk_gstin_status CHECK (status IN (0,1)),
    CONSTRAINT chk_gstin_format CHECK (gstin_number ~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$'),
    CONSTRAINT uq_gstins_number UNIQUE (gstin_number),
    CONSTRAINT fk_gstins_company FOREIGN KEY (company_id)
        REFERENCES companies (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_gstins_unit FOREIGN KEY (unit_id)
        REFERENCES units (id) ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX idx_gstins_company ON gstins (company_id);
CREATE INDEX idx_gstins_state ON gstins (state_code);

-- Table: users
CREATE TYPE user_status AS ENUM ('active','inactive','locked');
CREATE TABLE users (
