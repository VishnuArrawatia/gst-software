-- GST-SOFTWARE — Phase 0: reconciliation controls
--
-- Adds the four things the Accounts team needs that the file-based pipeline
-- could not hold: the ORIGINAL book values (immutable), the EDITABLE
-- reconciliation values, the human ITC decision, and an audit trail.
--
-- Why new tables instead of the Phase-1 tables already in this schema
-- (purchase_bills / purchase_reconciliation / reconciliation_corrections /
-- period_locks)?
--
--   * purchase_bills.uploaded_file_id is NOT NULL, party_id is NOT NULL and
--     company/unit/gstin are all NOT NULL, so a line cannot be stored without
--     inventing a party master row and an uploaded_files row for every run.
--   * reconciliation_corrections.corrected_by and period_locks.locked_by are
--     NOT NULL FKs to users, and users is empty — the app has no login yet
--     (spec §22 says do not add login in Phase 0).
--   * purchase_bills.chk_pb_nonnegative forbids a negative taxable/IGST/CGST/
--     SGST, which credit notes and 2B amendments legitimately carry.
--
-- So Phase 0 gets its own small, self-contained set of tables. Nothing in
-- 01/02/03 is altered, dropped or rewritten. When a real login arrives these
-- can be joined to users without a data move.
--
-- Golden rules encoded here
--   1. book_* columns are never updated by the application. There is a trigger
--      (trg_book_immutable) that makes that a database guarantee, not a code
--      convention — an accountant's evidence cannot be edited by accident or
--      by a bad migration.
--   2. Matching always uses recon_*. book_* is kept for proof only.
--   3. A locked period rejects every write to a line in it, including the ITC
--      decision. Unlock is itself recorded.

-- ===================================================================
-- PURCHASE LINES — book data + reconciliation data, side by side
-- ===================================================================

CREATE TABLE IF NOT EXISTS purchase_lines (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Deterministic identity of a book line across runs. The pipeline is
    -- reproducible (same file -> same rows in the same order), so
    -- our_gstin|period|source_file|source_row is stable and lets a re-run
    -- refresh the match result WITHOUT losing a recon edit or an ITC decision.
    line_key              TEXT NOT NULL UNIQUE,

    our_gstin             VARCHAR(15) NOT NULL,
    period                VARCHAR(7)  NOT NULL,
    financial_year        VARCHAR(9)  NOT NULL,
    gstin_id              INTEGER REFERENCES gstins (id) ON DELETE SET NULL,
    company_id            INTEGER REFERENCES companies (id) ON DELETE SET NULL,
    unit_name             TEXT,

    party_name            TEXT,
    source_file           TEXT,
    source_row            INTEGER,
    imported_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    import_source         VARCHAR(20) NOT NULL DEFAULT 'file',

    -- ---- BOOK DATA — written once at import, never changed again ----------
    book_supplier_gstin   VARCHAR(15) NOT NULL,
    book_invoice_no       VARCHAR(100) NOT NULL,
    book_invoice_date     DATE NOT NULL,
    book_taxable_value    NUMERIC(15,2) NOT NULL DEFAULT 0,
    book_igst             NUMERIC(15,2) NOT NULL DEFAULT 0,
    book_cgst             NUMERIC(15,2) NOT NULL DEFAULT 0,
    book_sgst             NUMERIC(15,2) NOT NULL DEFAULT 0,
    book_cess             NUMERIC(15,2) NOT NULL DEFAULT 0,

    -- ---- RECONCILIATION DATA — the three editable fields -----------------
    -- Seeded from the book values, then owned by the Accounts user.
    recon_supplier_gstin  VARCHAR(15) NOT NULL,
    recon_invoice_no      VARCHAR(100) NOT NULL,
    recon_invoice_date    DATE NOT NULL,
    recon_edited          BOOLEAN     NOT NULL DEFAULT false,
    recon_edited_by       TEXT,
    recon_edited_at       TIMESTAMPTZ,

    -- ---- MATCH OUTCOME — refreshed by every reconciliation ---------------
    match_status          VARCHAR(30),
    match_method          VARCHAR(30) NOT NULL DEFAULT 'primary',
    matched_2b_key        TEXT,
    -- The 2B month the line actually matched in, taken from the uploaded 2B
    -- file's own period (portal `fp`). Deliberately NOT the book period.
    matched_2b_month      VARCHAR(7),
    twob_supplier_gstin   VARCHAR(15),
    twob_invoice_no       VARCHAR(100),
    twob_invoice_date     DATE,
    twob_taxable_value    NUMERIC(15,2),
    twob_igst             NUMERIC(15,2),
    twob_cgst             NUMERIC(15,2),
    twob_sgst             NUMERIC(15,2),
    twob_cess             NUMERIC(15,2),
    twob_itc              NUMERIC(15,2),
    itc_availability      VARCHAR(20),
    mismatch_reason       TEXT,
    itc_amount            NUMERIC(15,2) NOT NULL DEFAULT 0,
    taxable_difference    NUMERIC(15,2),
    itc_difference        NUMERIC(15,2),
    duplicate_count       INTEGER,
    suggested_action      TEXT,
    reconciled_at         TIMESTAMPTZ,

    -- ---- ITC DECISION — made by a human, never by the software ----------
    itc_decision          VARCHAR(20) NOT NULL DEFAULT 'Pending Review',
    itc_decision_month    VARCHAR(7),
    decision_by           TEXT,
    decision_at           TIMESTAMPTZ,
    decision_reason       TEXT,
    -- Return treatment stays a separate, human-owned field. The software must
    -- not decide 4(A) / 4(A)(i) / 4(B) on its own (spec §15).
    return_classification VARCHAR(30) NOT NULL DEFAULT 'Pending Review',

    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_pl_gstin_period ON purchase_lines (our_gstin, period);
CREATE INDEX IF NOT EXISTS idx_pl_period        ON purchase_lines (period);
CREATE INDEX IF NOT EXISTS idx_pl_status        ON purchase_lines (match_status);
CREATE INDEX IF NOT EXISTS idx_pl_decision      ON purchase_lines (itc_decision);
CREATE INDEX IF NOT EXISTS idx_pl_decision_month ON purchase_lines (itc_decision_month);
CREATE INDEX IF NOT EXISTS idx_pl_matched_month ON purchase_lines (matched_2b_month);
CREATE INDEX IF NOT EXISTS idx_pl_recon_key
    ON purchase_lines (our_gstin, recon_supplier_gstin, recon_invoice_no);
CREATE INDEX IF NOT EXISTS idx_pl_vendor ON purchase_lines (party_name);

-- The three editable fields, spelled once so the API and the report cannot
-- drift apart.
COMMENT ON COLUMN purchase_lines.recon_supplier_gstin IS
    'Editable: supplier GSTIN used for matching. Defaults to book value.';
COMMENT ON COLUMN purchase_lines.matched_2b_month IS
    'Return period of the uploaded GSTR-2B file this line matched in (YYYY-MM).';
COMMENT ON COLUMN purchase_lines.itc_decision IS
    'Pending Review | Claim | Do Not Claim | Reclaim Later | Query Vendor | Ineligible | Reversed';

-- A GSTR-2B line count per month is worth an index for the registry screen.
CREATE TABLE IF NOT EXISTS gstr2b_lines (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_key              TEXT NOT NULL UNIQUE,

    our_gstin             VARCHAR(15) NOT NULL,
    supplier_gstin        VARCHAR(15) NOT NULL,
    supplier_name         TEXT,
    invoice_no            VARCHAR(100) NOT NULL,
    invoice_date          DATE,
    document_type         VARCHAR(30),

    taxable_value         NUMERIC(15,2) NOT NULL DEFAULT 0,
    igst                  NUMERIC(15,2) NOT NULL DEFAULT 0,
    cgst                  NUMERIC(15,2) NOT NULL DEFAULT 0,
    sgst                  NUMERIC(15,2) NOT NULL DEFAULT 0,
    cess                  NUMERIC(15,2) NOT NULL DEFAULT 0,
    invoice_value         NUMERIC(15,2) NOT NULL DEFAULT 0,

    -- The 2B month this line came from, i.e. the file's own return period.
    twob_month            VARCHAR(7)  NOT NULL,
    portal_fp             VARCHAR(7),
    filing_date           DATE,
    place_of_supply       VARCHAR(100),
    reverse_charge        BOOLEAN     NOT NULL DEFAULT false,
    itc_availability      VARCHAR(20) NOT NULL DEFAULT 'Yes',
    reason                TEXT,
    applicable_pct        VARCHAR(20),

    source_file           TEXT,
    source_row            INTEGER,
    source_format         VARCHAR(10) NOT NULL DEFAULT 'xlsx',
    imported_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_2bl_gstin_month ON gstr2b_lines (our_gstin, twob_month);
CREATE INDEX IF NOT EXISTS idx_2bl_match ON gstr2b_lines (our_gstin, supplier_gstin, invoice_no);

-- ===================================================================
-- 2B FILE REGISTRY — which portal file was uploaded, for which month
-- ===================================================================

CREATE TABLE IF NOT EXISTS gstr2b_files (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name         TEXT NOT NULL,
    sha256            CHAR(64) NOT NULL,
    file_size         BIGINT,
    our_gstin         VARCHAR(15) NOT NULL,
    company_id        INTEGER REFERENCES companies (id) ON DELETE SET NULL,
    financial_year    VARCHAR(9)  NOT NULL,
    -- 2B month this file is FOR (not the month it was downloaded in).
    twob_month        VARCHAR(7)  NOT NULL,
    portal_fp         VARCHAR(7),
    record_count      INTEGER NOT NULL DEFAULT 0,
    blocked_count     INTEGER NOT NULL DEFAULT 0,
    source_format     VARCHAR(10) NOT NULL DEFAULT 'xlsx',
    uploaded_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    uploaded_by       TEXT NOT NULL DEFAULT 'system',
    notes             TEXT
);
-- The same file may never be registered twice: that is the "do not create
-- duplicate 2B uploads silently" rule, enforced rather than trusted.
CREATE UNIQUE INDEX IF NOT EXISTS uq_2b_file ON gstr2b_files (our_gstin, twob_month, sha256);
CREATE INDEX IF NOT EXISTS idx_2bf_gstin_month ON gstr2b_files (our_gstin, twob_month);

-- ===================================================================
-- CORRECTION HISTORY — every recon edit, forever
-- ===================================================================

CREATE TABLE IF NOT EXISTS recon_corrections (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id           BIGINT NOT NULL REFERENCES purchase_lines (id) ON DELETE CASCADE,
    our_gstin         VARCHAR(15),
    period            VARCHAR(7),
    invoice_no        VARCHAR(100),
    supplier_gstin    VARCHAR(15),
    field_name        VARCHAR(40) NOT NULL,
    old_value         TEXT NOT NULL,
    new_value         TEXT NOT NULL,
    reason            TEXT,
    changed_by        TEXT NOT NULL DEFAULT 'unknown',
    changed_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Set when the edit is followed by a re-reconcile, so the trail proves the
    -- match was re-run and not just the text changed.
    rerefreshed       BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT ck_rc_field CHECK (
        field_name IN ('recon_supplier_gstin','recon_invoice_no','recon_invoice_date',
                       'itc_decision','itc_decision_month','return_classification')
    )
);
CREATE INDEX IF NOT EXISTS idx_rc_line ON recon_corrections (line_id, changed_at);
CREATE INDEX IF NOT EXISTS idx_rc_gstin_period ON recon_corrections (our_gstin, period);
CREATE INDEX IF NOT EXISTS idx_rc_changed_at ON recon_corrections (changed_at DESC);

-- ===================================================================
-- MONTH LOCK — a closed period is closed
-- ===================================================================

CREATE TABLE IF NOT EXISTS month_locks (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    our_gstin         VARCHAR(15) NOT NULL,
    company_id        INTEGER REFERENCES companies (id) ON DELETE SET NULL,
    financial_year    VARCHAR(9)  NOT NULL,
    period            VARCHAR(7)  NOT NULL,
    is_locked         BOOLEAN NOT NULL DEFAULT true,
    locked_by         TEXT NOT NULL DEFAULT 'unknown',
    locked_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    unlocked_by       TEXT,
    unlocked_at       TIMESTAMPTZ,
    unlock_reason     TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_month_lock ON month_locks (our_gstin, financial_year, period);

CREATE OR REPLACE FUNCTION block_write_to_locked_month()
RETURNS TRIGGER AS $$
DECLARE
    v_gstin TEXT;
    v_period TEXT;
BEGIN
    v_gstin := COALESCE(NEW.our_gstin, OLD.our_gstin);
    v_period := COALESCE(NEW.period, OLD.period);

    IF EXISTS (
        SELECT 1 FROM month_locks
        WHERE is_locked AND our_gstin = v_gstin AND period = v_period
    ) THEN
        RAISE EXCEPTION
            'GST month % for % is LOCKED. Unlock it (as admin) before making changes.', v_period, v_gstin
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_pl_line_lock ON purchase_lines;
CREATE TRIGGER trg_pl_line_lock
    BEFORE INSERT OR UPDATE OR DELETE ON purchase_lines
    FOR EACH ROW EXECUTE FUNCTION block_write_to_locked_month();

-- ===================================================================
-- AUDIT TRAIL — flat, field-level, the screen an auditor actually reads
-- ===================================================================

CREATE TABLE IF NOT EXISTS audit_trail (
    id                BIGSERIAL PRIMARY KEY,
    -- ts is the moment of the change; created_at exists so the table matches
    -- the rest of the schema's convention.
    ts                TIMESTAMPTZ NOT NULL DEFAULT now(),
    changed_by        TEXT NOT NULL DEFAULT 'unknown',
    action            VARCHAR(20) NOT NULL,
    our_gstin         VARCHAR(15),
    company           TEXT,
    financial_year    VARCHAR(9),
    period            VARCHAR(7),
    line_id           BIGINT,
    invoice_no        VARCHAR(100),
    supplier_gstin    VARCHAR(15),
    field_name        VARCHAR(40),
    old_value         TEXT,
    new_value         TEXT,
    reason            TEXT,
    details           JSONB
);
CREATE INDEX IF NOT EXISTS idx_at_ts ON audit_trail (ts DESC);
CREATE INDEX IF NOT EXISTS idx_at_gstin_period ON audit_trail (our_gstin, period);
CREATE INDEX IF NOT EXISTS idx_at_line ON audit_trail (line_id);
CREATE INDEX IF NOT EXISTS idx_at_field ON audit_trail (field_name);
CREATE INDEX IF NOT EXISTS idx_at_by ON audit_trail (changed_by);

-- ===================================================================
-- IMMUTABILITY — the accounting guarantee
-- ===================================================================

CREATE OR REPLACE FUNCTION trg_book_values_immutable()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.book_supplier_gstin IS DISTINCT FROM OLD.book_supplier_gstin
       OR NEW.book_invoice_no     IS DISTINCT FROM OLD.book_invoice_no
       OR NEW.book_invoice_date   IS DISTINCT FROM OLD.book_invoice_date
       OR NEW.book_taxable_value  IS DISTINCT FROM OLD.book_taxable_value
       OR NEW.book_igst           IS DISTINCT FROM OLD.book_igst
       OR NEW.book_cgst           IS DISTINCT FROM OLD.book_cgst
       OR NEW.book_sgst           IS DISTINCT FROM OLD.book_sgst
       OR NEW.book_cess           IS DISTINCT FROM OLD.book_cess THEN
        RAISE EXCEPTION
            'Book values are immutable. Reconcile by changing the recon_* fields, never the book_* fields.'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_pl_book_immutable ON purchase_lines;
CREATE TRIGGER trg_pl_book_immutable
    BEFORE UPDATE ON purchase_lines
    FOR EACH ROW EXECUTE FUNCTION trg_book_values_immutable();

-- ===================================================================
-- Raw row-level audit, using the Phase-1 trigger, on the Phase-0 tables
-- ===================================================================

DO $$
DECLARE
    tbl TEXT;
    t TEXT[] := ARRAY['purchase_lines','gstr2b_lines','gstr2b_files',
                      'recon_corrections','month_locks'];
BEGIN
    FOREACH tbl IN ARRAY t LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS tg_audit_%I ON %I', tbl, tbl);
        EXECUTE format(
            'CREATE TRIGGER tg_audit_%I AFTER INSERT OR UPDATE OR DELETE ON %I
             FOR EACH ROW EXECUTE FUNCTION fn_audit_log()', tbl, tbl);
    END LOOP;
END $$;
