-- 17_profit_and_loss_vs_gstr1.sql
--
-- P&L vs GSTR-1 RECONCILIATION
--
-- The chain this module controls, per company, per financial year, per month,
-- and always retaining GSTIN-level detail:
--
--     COMBINED P&L  ->  P&L GST MAPPING  ->  GSTIN-1 + GSTIN-2 (+ n)
--                  ->  COMBINED BOOKS   ->  GSTR-1  ->  GSTR-3B  ->  GST PAYABLE
--
-- The P&L is combined at company level, but GST lives per GSTIN. The GSTIN-wise
-- figures are summed into a combined GST position, and THAT is compared with the
-- combined P&L. The GSTIN detail is never collapsed or overwritten: it is always
-- available beneath the combined number.
--
-- This replaces the quarantined m10/10_truncated_do_not_use.sql, which was cut
-- off mid-statement and could not be applied. Everything below is additive: no
-- existing table is dropped or altered, only two columns are added to
-- sales_invoices, and only to widen the model.
--
-- Source tables are append-only, enforced by triggers rather than by convention.

-- -------------------------------------------------------------------
-- P&L HEAD MASTER
--
-- One row per P&L line a company reports. `sequence` exists so a P&L can be
-- printed and reconciled in its own order rather than alphabetically, and
-- `head_kind` keeps credit and debit notes from being silently netted into the
-- sale heads.
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pl_heads (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id   INTEGER NOT NULL REFERENCES companies (id) ON DELETE RESTRICT,
    name         VARCHAR(255) NOT NULL,
    group_name   VARCHAR(100) NOT NULL DEFAULT 'Turnover',
    sequence     INTEGER NOT NULL DEFAULT 100,
    head_kind    VARCHAR(20) NOT NULL DEFAULT 'SALE',
    is_mandatory SMALLINT NOT NULL DEFAULT 0,
    remarks      TEXT,
    status       SMALLINT NOT NULL DEFAULT 1,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by   INTEGER,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by   INTEGER,
    CONSTRAINT ck_plh_status CHECK (status IN (0,1)),
    CONSTRAINT ck_plh_kind   CHECK (head_kind IN ('SALE','CREDIT_NOTE','DEBIT_NOTE','OTHER_INCOME','EXPENSE'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_pl_head ON pl_heads (company_id, lower(name));
CREATE INDEX IF NOT EXISTS idx_pl_head_company ON pl_heads (company_id, sequence);

COMMENT ON TABLE pl_heads IS
    'P&L lines a company reports. is_mandatory marks the five GST outward heads seeded for every company; they may be renamed but not deleted while entries exist.';

-- -------------------------------------------------------------------
-- GST MAPPING MASTER
--
-- How each P&L head is treated for GST. Deliberately separate from pl_heads so
-- a head's P&L identity and its GST treatment can change independently and both
-- histories survive.
--
-- Other Income is NOT assumed taxable: gst_applicable is a real choice, and
-- anything mapped false is reported as "Outside GST Reconciliation" rather than
-- being forced into a return.
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pl_gst_mapping (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pl_head_id       INTEGER NOT NULL REFERENCES pl_heads (id) ON DELETE CASCADE,
    gst_applicable   BOOLEAN NOT NULL DEFAULT true,
    gst_nature       VARCHAR(60) NOT NULL DEFAULT 'Outward Supply',
    return_mapping   VARCHAR(60) NOT NULL DEFAULT 'GSTR-1',
    gstr1_table      VARCHAR(60),
    gstr3b_mapping   VARCHAR(60),
    taxable_type     VARCHAR(30) NOT NULL DEFAULT 'Taxable',
    exempt_or_nil    VARCHAR(20),
    include_in_gstr1 BOOLEAN NOT NULL DEFAULT true,
    remarks          TEXT,
    status           SMALLINT NOT NULL DEFAULT 1,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by       INTEGER,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by       INTEGER,
    CONSTRAINT ck_pgm_status CHECK (status IN (0,1)),
    CONSTRAINT ck_pgm_ttype  CHECK (taxable_type IN ('Taxable','Non-Taxable','Exempt','Nil Rated','Not Applicable')),
    CONSTRAINT ck_pgm_exn    CHECK (exempt_or_nil IS NULL OR exempt_or_nil IN ('Exempt','Nil Rated'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_pgm_head ON pl_gst_mapping (pl_head_id);

-- -------------------------------------------------------------------
-- P&L ENTRIES — SOURCE DATA, APPEND ONLY
--
-- Imported from the company's combined P&L. A corrected P&L is a NEW version
-- (amendment_no), never an edit of the old one. Re-importing the same file is
-- safe because the unique key collides instead of double counting.
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pl_entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id     INTEGER NOT NULL REFERENCES companies (id) ON DELETE RESTRICT,
    pl_head_id     INTEGER NOT NULL REFERENCES pl_heads (id) ON DELETE RESTRICT,
    period         VARCHAR(7) NOT NULL,
    financial_year VARCHAR(9) NOT NULL,
    amount         NUMERIC(15,2) NOT NULL DEFAULT 0,
    source_file    VARCHAR(255) NOT NULL,
    source_row     INTEGER NOT NULL,
    amendment_no   INTEGER NOT NULL DEFAULT 0,
    -- The amount exactly as it appeared in the file, so a re-parse can be
    -- compared against what we stored rather than trusted.
    raw_amount     NUMERIC(15,2),
    uploaded_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    uploaded_by    INTEGER
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_pl_entry
    ON pl_entries (company_id, pl_head_id, period, source_file, source_row, amendment_no);
CREATE INDEX IF NOT EXISTS idx_pl_entry_period ON pl_entries (company_id, period);
CREATE INDEX IF NOT EXISTS idx_pl_entry_fy     ON pl_entries (financial_year, company_id);

-- Append-only, enforced in the database rather than by convention.
--
-- The escape hatch exists for one reason: maintenance and the test harness must
-- be able to remove fixture rows, and there is no way to grant that without
-- weakening the rule. A caller sets `SET LOCAL app.allow_pl_mutation = 'on'`
-- inside its own transaction, so the bypass is explicit, scoped and never part
-- of a normal import.
CREATE OR REPLACE FUNCTION fn_pl_entries_immutable() RETURNS trigger AS $$
BEGIN
    IF coalesce(current_setting('app.allow_pl_mutation', true), 'off') = 'on' THEN
        RETURN CASE TG_OP WHEN 'DELETE' THEN OLD ELSE NEW END;
    END IF;
    RAISE EXCEPTION
        'P&L source data is immutable. Import a corrected P&L as a new '
        'amendment_no instead of editing or deleting a row. (%.%.%)',
        TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_OP;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_pl_entries_immutable ON pl_entries;
CREATE TRIGGER trg_pl_entries_immutable
    BEFORE UPDATE OR DELETE ON pl_entries
    FOR EACH ROW EXECUTE FUNCTION fn_pl_entries_immutable();

