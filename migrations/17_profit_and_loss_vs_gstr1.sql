-- -------------------------------------------------------------------
-- OTHER INCOME — TAX TREATMENT
--
-- Other Income is taxable only if the company says so, and the answer can
-- change month to month. Keeping it in its own table means the decision is
-- recorded rather than inferred from the mapping default.
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS other_income_tax_treatment (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id     INTEGER NOT NULL REFERENCES companies (id) ON DELETE RESTRICT,
    pl_head_id     INTEGER NOT NULL REFERENCES pl_heads (id) ON DELETE CASCADE,
    financial_year VARCHAR(9) NOT NULL,
    period         VARCHAR(7) NOT NULL,
    treatment      VARCHAR(40) NOT NULL,
    remarks        TEXT,
    decided_by     INTEGER,
    decided_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_oit_head FOREIGN KEY (pl_head_id) REFERENCES pl_heads (id) ON DELETE CASCADE,
    CONSTRAINT ck_oit_trt  CHECK (treatment IN ('Outside GST','Exempt','Nil Rated','Taxable')),
    CONSTRAINT uq_oit_scope UNIQUE (company_id, pl_head_id, period)
);
CREATE INDEX IF NOT EXISTS idx_oit_company ON other_income_tax_treatment (company_id, period);

COMMENT ON TABLE other_income_tax_treatment IS
    'Per-month decision on whether a given Other Income head is taxable. Outside GST means the amount is reported but never forced into a return.';

-- -------------------------------------------------------------------
-- P&L RECONCILIATION RESULT
--
-- One row per head per period: what the P&L says, what GSTR-1 says, the
-- difference, and the reason that explains it. A non-zero difference with no
-- reason is rejected by the CHECK below rather than stored.
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pl_reconciliation (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id        INTEGER NOT NULL REFERENCES companies (id) ON DELETE RESTRICT,
    financial_year    VARCHAR(9) NOT NULL,
    period            VARCHAR(7) NOT NULL,
    pl_head_id        INTEGER NOT NULL REFERENCES pl_heads (id) ON DELETE RESTRICT,
    gstr1_table       VARCHAR(60),
    -- Latest amendment wins; older ones stay in pl_entries as history.
    amendment_no      INTEGER NOT NULL DEFAULT 0,

    pl_amount         NUMERIC(15,2) NOT NULL DEFAULT 0,
    gstr1_amount      NUMERIC(15,2) NOT NULL DEFAULT 0,
    difference        NUMERIC(15,2) NOT NULL DEFAULT 0,

    -- GSTIN-wise detail is summed for the comparison but never lost.
    gstin_breakdown   JSONB NOT NULL DEFAULT '[]'::jsonb,
    -- The GSTINs whose documents produced the GSTR-1 figure, for the drill-down.
    gstin_count       INTEGER NOT NULL DEFAULT 0,

    difference_reason VARCHAR(60) REFERENCES recon_difference_reasons (code),
    remarks           TEXT,
    status            VARCHAR(30) NOT NULL DEFAULT 'Pending Review',
    is_locked         BOOLEAN NOT NULL DEFAULT false,
    reconciled_by     INTEGER,
    reconciled_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_plr_status CHECK (status IN
        ('Pending Review','Reconciled','Difference Explained','Difference Unresolved','Not Mapped')),
    -- A difference must be explained. This is the whole point of the module,
    -- so it is enforced by the database and not only by the screen.
    CONSTRAINT ck_plr_reason CHECK (difference = 0 OR difference_reason IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_pl_recon
    ON pl_reconciliation (company_id, period, pl_head_id, amendment_no);
CREATE INDEX IF NOT EXISTS idx_plr_period ON pl_reconciliation (company_id, period);
CREATE INDEX IF NOT EXISTS idx_plr_status ON pl_reconciliation (status);

