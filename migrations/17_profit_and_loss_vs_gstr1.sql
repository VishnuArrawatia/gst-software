-- -------------------------------------------------------------------
-- v_pl_vs_books
--
-- The read model the screen and the reports both use, so the two can never
-- disagree. GSTIN detail rides along in gstin_breakdown instead of being
-- collapsed away.
-- -------------------------------------------------------------------
CREATE OR REPLACE VIEW v_pl_vs_books AS
SELECT
    r.id                AS recon_id,
    r.company_id,
    co.name             AS company_name,
    r.financial_year,
    r.period,
    h.id                AS pl_head_id,
    h.name              AS pl_head,
    h.group_name,
    h.head_kind,
    h.sequence,
    h.is_mandatory,
    m.gst_applicable,
    m.taxable_type,
    m.return_mapping,
    r.gstr1_table,
    m.include_in_gstr1,
    r.amendment_no,
    r.pl_amount,
    r.gstr1_amount,
    r.difference,
    r.gstin_count,
    r.gstin_breakdown,
    r.difference_reason,
    dr.label            AS difference_reason_label,
    dr.category         AS difference_category,
    r.remarks,
    r.status,
    r.is_locked,
    r.reconciled_by,
    r.reconciled_at
FROM pl_reconciliation r
JOIN pl_heads h        ON h.id = r.pl_head_id
JOIN companies co      ON co.id = r.company_id
LEFT JOIN pl_gst_mapping m ON m.pl_head_id = h.id AND m.status = 1
LEFT JOIN recon_difference_reasons dr ON dr.code = r.difference_reason;

COMMENT ON VIEW v_pl_vs_books IS
    'P&L head versus the combined GSTR-1 figure for that head. One row per head per month; gstin_breakdown carries the GSTIN detail.';

-- -------------------------------------------------------------------
-- THE FIVE MANDATORY GST OUTWARD HEADS
--
-- Seeded for every company so the module is usable the moment it is switched
-- on. Names are the starting point, not a cage: is_mandatory only marks the
-- five heads a reconciliation is expected to cover, and a company can rename
-- them or add its own lines. Other Income is seeded too, deliberately mapped
-- OUTSIDE GST, because assuming it taxable would push an amount into a return
-- that the law may not require.
-- -------------------------------------------------------------------
INSERT INTO pl_heads (company_id, name, group_name, sequence, head_kind, is_mandatory, remarks)
SELECT c.id, v.name, v.group_name, v.sequence, v.head_kind, v.is_mandatory, v.remarks
FROM companies c
CROSS JOIN (VALUES
    ('Taxable Sales',                     'Turnover',      10, 'SALE',          1, 'B2B, B2CL and B2CS taxable supplies. The main outward line.'),
    ('Export Sales',                      'Turnover',      20, 'SALE',          1, 'Zero rated exports, GSTR-1 table EXP.'),
    ('Exempt Sales',                      'Turnover',      30, 'SALE',          1, 'Exempt supplies. Declared, never taxed.'),
    ('Nil / Zero Rated Sales',            'Turnover',      40, 'SALE',          1, 'Nil rated domestic supplies, GSTR-1 table NIL.'),
    ('Credit Notes / Sales Returns',      'Turnover',      50, 'CREDIT_NOTE',   1, 'GSTR-1 table CDNR. Never netted into Taxable Sales.'),
    ('Other Income',                      'Other Income',  60, 'OTHER_INCOME',  0, 'Outside GST by default. Record the treatment per month rather than assuming.')
) AS v(name, group_name, sequence, head_kind, is_mandatory, remarks)
WHERE NOT EXISTS (
    SELECT 1 FROM pl_heads h WHERE h.company_id = c.id AND lower(h.name) = lower(v.name)
);

INSERT INTO pl_gst_mapping (pl_head_id, gst_applicable, gst_nature, return_mapping, gstr1_table, taxable_type, include_in_gstr1, remarks)
SELECT h.id,
       m.gst_applicable,
       m.gst_nature,
       m.return_mapping,
       m.gstr1_table,
       m.taxable_type,
       m.include_in_gstr1,
       m.remarks
FROM pl_heads h
JOIN (VALUES
    ('Taxable Sales',                true,  'Outward Supply', 'GSTR-1', 'B2B/B2CL/B2CS', 'Taxable',          true,  NULL),
    ('Export Sales',                 true,  'Export',         'GSTR-1', 'EXP',           'Nil Rated',        true,  NULL),
    ('Exempt Sales',                 true,  'Exempt Supply',  'GSTR-1', 'EXEMPT',        'Exempt',           true,  NULL),
    ('Nil / Zero Rated Sales',       true,  'Nil Rated',      'GSTR-1', 'NIL',           'Nil Rated',        true,  NULL),
    ('Credit Notes / Sales Returns', true,  'Credit Note',    'GSTR-1', 'CDNR',          'Taxable',          true,  NULL),
    ('Other Income',                 false, 'Outside GST',    'None',   NULL,            'Not Applicable',  false, 'Taxability is a per-month decision; record it in other_income_tax_treatment.')
) AS m(head_name, gst_applicable, gst_nature, return_mapping, gstr1_table, taxable_type, include_in_gstr1, remarks)
  ON m.head_name = h.name
WHERE NOT EXISTS (SELECT 1 FROM pl_gst_mapping g WHERE g.pl_head_id = h.id);