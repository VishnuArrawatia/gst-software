-- ===================================================================
-- ITC CONTROL — the running credit ledger
--
-- Input tax credit is an ASSET, not a monthly P&L number. A month with heavy
-- purchases and no sales builds a balance that must carry forward, and the
-- whole point of this table is that the balance is stored rather than
-- recomputed from scratch each time you ask for it. A UNIQUE on
-- (gstin, period) plus the opening/closing columns makes the ledger
-- self-auditing: closing of one period must equal opening of the next.
-- ===================================================================

CREATE TABLE IF NOT EXISTS itc_period_ledger (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gstin_id            INTEGER NOT NULL,
    financial_year      VARCHAR(9) NOT NULL,
    period              VARCHAR(6) NOT NULL,

    purchase_rows       INTEGER NOT NULL DEFAULT 0,
    twob_rows           INTEGER NOT NULL DEFAULT 0,
    matched_rows        INTEGER NOT NULL DEFAULT 0,

    books_itc           NUMERIC(15,2) NOT NULL DEFAULT 0,
    claimable_itc       NUMERIC(15,2) NOT NULL DEFAULT 0,
    blocked_itc         NUMERIC(15,2) NOT NULL DEFAULT 0,
    pending_4ai_itc     NUMERIC(15,2) NOT NULL DEFAULT 0,
    duplicate_itc       NUMERIC(15,2) NOT NULL DEFAULT 0,
    itc_availed         NUMERIC(15,2) NOT NULL DEFAULT 0,

    output_tax          NUMERIC(15,2) NOT NULL DEFAULT 0,
    opening_credit      NUMERIC(15,2) NOT NULL DEFAULT 0,
    itc_utilised        NUMERIC(15,2) NOT NULL DEFAULT 0,
    closing_credit      NUMERIC(15,2) NOT NULL DEFAULT 0,

    -- cl.16(4)(d): ITC for an FY lapses after 30 Nov of the following FY.
    lapse_deadline      DATE,
    calculated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_itc_gstin FOREIGN KEY (gstin_id) REFERENCES gstins (id) ON DELETE RESTRICT,
    CONSTRAINT uq_itc_period UNIQUE (gstin_id, period),
    CONSTRAINT ck_itc_balances CHECK (closing_credit = opening_credit + itc_availed - itc_utilised)
);

-- Vendor-level credit leakage, ranked. Answering "who keeps costing us ITC"
-- is a monthly conversation, not an annual audit.
CREATE TABLE IF NOT EXISTS vendor_credit_exposure (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gstin_id            INTEGER NOT NULL,
    party_id            INTEGER,
    supplier_gstin      VARCHAR(15) NOT NULL,
    financial_year      VARCHAR(9) NOT NULL,
    invoices            INTEGER NOT NULL DEFAULT 0,
    books_itc           NUMERIC(15,2) NOT NULL DEFAULT 0,
    blocked_itc         NUMERIC(15,2) NOT NULL DEFAULT 0,
    missing_itc         NUMERIC(15,2) NOT NULL DEFAULT 0,
    duplicate_itc       NUMERIC(15,2) NOT NULL DEFAULT 0,
    cost_itc            NUMERIC(15,2) NOT NULL DEFAULT 0,
    calculated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_vce_gstin FOREIGN KEY (gstin_id) REFERENCES gstins (id) ON DELETE RESTRICT,
    CONSTRAINT uq_vce UNIQUE (gstin_id, financial_year, supplier_gstin)
);
CREATE INDEX IF NOT EXISTS idx_vce_rank ON vendor_credit_exposure (gstin_id, financial_year, cost_itc DESC);

-- ===================================================================
-- Period lock guard
--
-- A period that has been filed must not be silently recomputed by a later
-- import. period_locks already exists in Phase 1; this trigger is what makes
-- it actually enforced.
-- ===================================================================

CREATE OR REPLACE FUNCTION block_write_to_locked_period()
RETURNS TRIGGER AS $$
DECLARE
    v_gstin INTEGER;
    v_fy    VARCHAR(9);
    v_pr    VARCHAR(6);
BEGIN
    v_gstin := COALESCE(NEW.gstin_id, OLD.gstin_id);
    v_fy    := COALESCE(NEW.financial_year, OLD.financial_year);
    v_pr    := COALESCE(NEW.period, OLD.period);

    IF EXISTS (
        SELECT 1 FROM period_locks
        WHERE is_locked
          AND (gstin_id = v_gstin OR gstin_id IS NULL)
          AND financial_year = v_fy
          AND period = v_pr
    ) THEN
        RAISE EXCEPTION
            'Period % of GSTIN % is locked. Unlock it first if this change is intended.', v_pr, v_gstin
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sales_lock ON sales_invoices;
CREATE TRIGGER trg_sales_lock
    BEFORE INSERT OR UPDATE OR DELETE ON sales_invoices
    FOR EACH ROW EXECUTE FUNCTION block_write_to_locked_period();

-- ===================================================================
-- Reporting view — the ITC control screen in one query
-- ===================================================================

CREATE OR REPLACE VIEW v_itc_control AS
SELECT
    g.gstin_number,
    c.name                AS company_name,
    u.name                AS unit_name,
    l.financial_year,
    l.period,
    l.opening_credit,
    l.books_itc,
    l.claimable_itc,
    l.blocked_itc,
    l.pending_4ai_itc,
    l.duplicate_itc,
    l.itc_availed,
    l.output_tax,
    l.itc_utilised,
    l.closing_credit,
    l.lapse_deadline,
    CASE
        WHEN l.lapse_deadline < CURRENT_DATE THEN 'LAPSED'
        WHEN l.lapse_deadline < CURRENT_DATE + INTERVAL '60 days' THEN 'URGENT'
        WHEN l.closing_credit > 0 THEN 'AT RISK'
        ELSE 'CLEAR'
    END AS lapse_status
FROM itc_period_ledger l
JOIN gstins  g ON g.id = l.gstin_id
JOIN companies c ON c.id = g.company_id
LEFT JOIN units u ON u.id = g.unit_id
ORDER BY g.gstin_number, l.financial_year, l.period;
