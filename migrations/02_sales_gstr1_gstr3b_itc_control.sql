-- GST-SOFTWARE — Phase 2: outward side, returns, and ITC control
--
-- Extends 01_initialize_schema.sql, which already covers masters (companies,
-- units, gstins), security (users/roles/permissions), parties, periods, file
-- upload tracking, purchase_bills, gstr2b_records and purchase_reconciliation.
--
-- This file adds everything the OUTWARD side and the returns need:
--   sales_invoices      books side for GSTR-1
--   sales_reconciliation books sales vs what was declared in GSTR-1
--   gstr1_filings        one row per filed GSTR-1, with its portal totals
--   gstr3b_filings       one row per filed GSTR-3B
--   itc_period_ledger    running ITC balance per GSTIN per period
--
-- Design notes
--   * Every money column is NUMERIC(15,2) and every rate is NUMERIC(6,3).
--     Floating point would drift on crores of rupees and a 0.01 difference
--     between 4(A) and the portal is a rejected return.
--   * Raw and normalised values are both stored. Normalised columns are what
--     reconciliation matches on; raw columns are what gets shown to a human and
--     what lets us prove what the source file actually said.
--   * Uniqueness is on the NORMALISED key, because "INV/001" and "INV 001" are
--     one invoice and must not both load.

-- ===================================================================
-- SALES REGISTER — the outward books side, drives GSTR-1
-- ===================================================================

CREATE TABLE IF NOT EXISTS sales_invoices (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gstin_id                    INTEGER NOT NULL,
    company_id                  INTEGER NOT NULL,
    unit_id                     INTEGER,

    customer_id                 INTEGER,
    customer_gstin_raw          VARCHAR(15),
    customer_gstin_norm         VARCHAR(15),
    customer_name               VARCHAR(255),

    invoice_number_raw          VARCHAR(100) NOT NULL,
    invoice_number_norm         VARCHAR(100) NOT NULL,
    invoice_date                DATE        NOT NULL,
    financial_year              VARCHAR(9)  NOT NULL,
    period                      VARCHAR(6)  NOT NULL,

    invoice_type                VARCHAR(8)  NOT NULL DEFAULT 'R',
    place_of_supply             VARCHAR(100),
    reverse_charge              BOOLEAN     NOT NULL DEFAULT false,
    hsn                         VARCHAR(8),

    taxable_value               NUMERIC(15,2) NOT NULL DEFAULT 0,
    igst                        NUMERIC(15,2) NOT NULL DEFAULT 0,
    cgst                        NUMERIC(15,2) NOT NULL DEFAULT 0,
    sgst                        NUMERIC(15,2) NOT NULL DEFAULT 0,
    cess                        NUMERIC(15,2) NOT NULL DEFAULT 0,
    invoice_value               NUMERIC(15,2) NOT NULL DEFAULT 0,

    -- CDNR only: the invoice being credited or debited. The portal rejects a
    -- note without these, so they are enforced rather than left to the CA.
    note_ref_number             VARCHAR(100),
    note_ref_date               DATE,

    uploaded_file_id            INTEGER,
    source_row_number           INTEGER,
    is_deleted                  BOOLEAN     NOT NULL DEFAULT false,
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_si_gstin   FOREIGN KEY (gstin_id)   REFERENCES gstins (id) ON DELETE RESTRICT,
    CONSTRAINT fk_si_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT ck_si_invoice_type CHECK (invoice_type IN ('R','SEZWP','SEWOP','DE','CDNR','DN','CANCEL'))
);

-- One invoice per GSTIN. Deliberately on the normalised number so that a
-- differently punctuated re-import collides instead of duplicating.
CREATE UNIQUE INDEX IF NOT EXISTS uq_sales_invoice
    ON sales_invoices (gstin_id, invoice_number_norm, invoice_date);
CREATE INDEX IF NOT EXISTS idx_sales_period  ON sales_invoices (gstin_id, period);
CREATE INDEX IF NOT EXISTS idx_sales_fy      ON sales_invoices (financial_year, gstin_id);
CREATE INDEX IF NOT EXISTS idx_sales_customer ON sales_invoices (customer_gstin_norm);

-- ===================================================================
-- SALES RECONCILIATION — books sales vs what was declared in GSTR-1
-- ===================================================================

CREATE TYPE sales_recon_status AS ENUM (
    'Matched',
    'Not Declared',
    'Not Booked',
    'Declared Not In Books',
    'Amount Mismatch',
    'Duplicate',
    'Credit Note Missing Ref'
);

CREATE TABLE IF NOT EXISTS sales_reconciliation (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_invoice_id       BIGINT,
    gstin_id               INTEGER NOT NULL,
    period                 VARCHAR(6) NOT NULL,
    status                 sales_recon_status NOT NULL,
    difference_amount      NUMERIC(15,2),
    difference_details     JSONB,
    resolved_by            INTEGER,
    resolved_at            TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_sr_invoice FOREIGN KEY (sales_invoice_id) REFERENCES sales_invoices (id) ON DELETE CASCADE,
    CONSTRAINT fk_sr_gstin   FOREIGN KEY (gstin_id)       REFERENCES gstins (id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_sales_recon ON sales_reconciliation (sales_invoice_id);
CREATE INDEX IF NOT EXISTS idx_sales_recon_exceptions
    ON sales_reconciliation (gstin_id, period)
    WHERE status <> 'Matched';

